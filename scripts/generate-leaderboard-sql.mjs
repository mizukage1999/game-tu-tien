import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { createServer } from 'vite';

const server = await createServer({
  configFile: false,
  envFile: false,
  server: { middlewareMode: true, watch: null },
});
try {
  const { ITEMS, SKILLS, DUNGEONS, EQUIP_SLOTS } = await server.ssrLoadModule('/src/data/index.ts');
  const { HEROES } = await server.ssrLoadModule('/src/data/heroes.ts');
  const { heroDefaultLoadout } = await server.ssrLoadModule('/src/data/heroSkills.ts');
  const { retiredSkill } = await server.ssrLoadModule('/src/data/skillCatalog.ts');
  const { COMPANIONS } = await server.ssrLoadModule('/src/game/systems/life.ts');
  const { SECT_RANKS } = await server.ssrLoadModule('/src/game/systems/adventure.ts');
  const { computeStats, realmNameAtLevel, MAX_LEVEL } = await server.ssrLoadModule(
    '/src/game/systems/progression.ts',
  );
  const payload = {
    maxLevel: MAX_LEVEL,
    sectRanks: SECT_RANKS,
    levels: Object.fromEntries(
      Array.from({ length: MAX_LEVEL }, (_, i) => {
        const level = i + 1,
          realm = Math.floor(i / 10);
        return [
          level,
          {
            realmIndex: realm,
            realm: realmNameAtLevel(level),
            stats: computeStats(level, realm, {}),
          },
        ];
      }),
    ),
    heroes: Object.fromEntries(
      HEROES.map((h) => [
        h.id,
        { sex: h.sex, school: h.school, loadout: heroDefaultLoadout(h.id) },
      ]),
    ),
    slots: EQUIP_SLOTS.map((s) => s.id),
    items: Object.fromEntries(
      Object.entries(ITEMS)
        .filter(([, i]) => i.slot)
        .map(([id, i]) => [
          id,
          {
            slot: i.slot,
            bonus: i.bonus ?? {},
            enhanced: Array.from({ length: 13 }, (_, n) => ({
              atk: Math.round((i.bonus?.atk ?? 0) * n * 0.12),
              def: Math.round((i.bonus?.def ?? 0) * n * 0.12),
              hp: Math.round((i.bonus?.hp ?? 0) * n * 0.12),
            })),
          },
        ]),
    ),
    companions: Object.fromEntries(
      COMPANIONS.map((c) => [c.id, { atk: c.atk, def: c.def, hp: c.hp }]),
    ),
    skills: Object.fromEntries(
      Object.entries(SKILLS)
        .filter(([id]) => !retiredSkill(id))
        .map(([id, s]) => [
          id,
          {
            ...(s.hero ? { hero: s.hero } : {}),
            ...(s.character ? { character: s.character } : {}),
            unlockLevel: s.unlockLevel ?? 1,
            secret: !!s.secret,
          },
        ]),
    ),
    dungeons: Object.keys(DUNGEONS),
  };
  const version = createHash('sha256').update(JSON.stringify(payload)).digest('hex').slice(0, 16);
  let accented = '',
    plain = '';
  for (let cp = 0xc0; cp <= 0x1ef9; cp++) {
    const char = String.fromCharCode(cp),
      folded = char.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    if (folded.length === 1 && /[aAeEiIoOuUyY]/.test(folded) && char !== folded) {
      accented += char;
      plain += folded;
    }
  }
  accented += 'đĐ';
  plain += 'dD';
  const quote = (s) => "'" + s.replaceAll("'", "''") + "'";
  const sql = fs
    .readFileSync('scripts/sql/leaderboard.template.sql', 'utf8')
    .replace(
      '-- @BALANCE_CATALOG@',
      () =>
        `insert into game_rank_private.balance(id,version,data) values(true,${quote(version)},${quote(JSON.stringify(payload))}::jsonb) on conflict(id) do update set version=excluded.version,data=excluded.data;`,
    )
    .replace(
      '-- @FOLD_FUNCTION@',
      () =>
        `create or replace function game_rank_private.fold(p_text text) returns text language sql immutable set search_path='' as $$ select lower(translate(normalize(coalesce(p_text,''),NFC),${quote(accented)},${quote(plain)})) $$;`,
    );
  fs.writeFileSync(
    'supabase/leaderboard.sql',
    '-- Generated by node scripts/generate-leaderboard-sql.mjs.\n' + sql,
  );
  console.log(
    `Leaderboard SQL generated; balance ${version}, ${Object.keys(payload.items).length} equipment definitions.`,
  );
} finally {
  await server.close();
}
