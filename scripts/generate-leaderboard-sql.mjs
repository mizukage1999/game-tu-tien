import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { createServer } from 'vite';

const server = await createServer({
  configFile: false,
  envFile: false,
  server: { middlewareMode: true, watch: null },
});
try {
  const { ITEMS, SKILLS, DUNGEONS, EQUIP_SLOTS, REALMS } =
    await server.ssrLoadModule('/src/data/index.ts');
  const { HEROES } = await server.ssrLoadModule('/src/data/heroes.ts');
  const { OUTFITS, WEAPON_SKINS } = await server.ssrLoadModule('/src/data/cosmetics.ts');
  const { heroDefaultLoadout } = await server.ssrLoadModule('/src/data/heroSkills.ts');
  const { retiredSkill } = await server.ssrLoadModule('/src/data/skillCatalog.ts');
  const { COMPANIONS } = await server.ssrLoadModule('/src/game/systems/life.ts');
  const { SECT_RANKS } = await server.ssrLoadModule('/src/game/systems/adventure.ts');
  const { computeStats, realmNameAtLevel, MAX_LEVEL, MAX_PROFILE_LEVEL } =
    await server.ssrLoadModule('/src/game/systems/progression.ts');
  const payload = {
    maxLevel: MAX_PROFILE_LEVEL,
    progressionMaxLevel: MAX_LEVEL,
    sectRanks: SECT_RANKS,
    cosmetics: {outfit:OUTFITS.map(x=>x.id),weapon:WEAPON_SKINS.map(x=>x.id)},
    levels: Object.fromEntries(
      Array.from({ length: MAX_PROFILE_LEVEL }, (_, i) => {
        const level = i + 1,
          realm = Math.min(REALMS.length - 1, Math.floor(i / 10));
        return [
          level,
          {
            realmIndex: realm,
            realm: realmNameAtLevel(level),
            stats: computeStats(level, realm, {}),
          },
        ];
      }),
    ),
    heroes: Object.fromEntries(
      HEROES.map((h) => [
        h.id,
        { sex: h.sex, school: h.school, loadout: heroDefaultLoadout(h.id) },
      ]),
    ),
    slots: EQUIP_SLOTS.map((s) => s.id),
    items: Object.fromEntries(
      Object.entries(ITEMS)
        .filter(([, i]) => i.slot)
        .map(([id, i]) => [
          id,
          {
            slot: i.slot,
            bonus: i.bonus ?? {},
            enhanced: Array.from({ length: 13 }, (_, n) => ({
              atk: Math.round((i.bonus?.atk ?? 0) * n * 0.12),
              def: Math.round((i.bonus?.def ?? 0) * n * 0.12),
              hp: Math.round((i.bonus?.hp ?? 0) * n * 0.12),
            })),
          },
        ]),
    ),
    companions: Object.fromEntries(
      COMPANIONS.map((c) => [c.id, { atk: c.atk, def: c.def, hp: c.hp }]),
    ),
    skills: Object.fromEntries(
      Object.entries(SKILLS)
        .filter(([id]) => !retiredSkill(id))
        .map(([id, s]) => [
          id,
          {
            ...(s.hero ? { hero: s.hero } : {}),
            ...(s.character ? { character: s.character } : {}),
            unlockLevel: s.unlockLevel ?? 1,
            secret: !!s.secret,
          },
        ]),
    ),
    dungeons: Object.keys(DUNGEONS),
  };
  const version = createHash('sha256').update(JSON.stringify(payload)).digest('hex').slice(0, 16);
  let accented = '',
    plain = '';
  for (let cp = 0xc0; cp <= 0x1ef9; cp++) {
    const char = String.fromCharCode(cp),
      folded = char.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    if (folded.length === 1 && /[aAeEiIoOuUyY]/.test(folded) && char !== folded) {
      accented += char;
      plain += folded;
    }
  }
  accented += 'đĐ';
  plain += 'dD';
  const quote = (s) => "'" + s.replaceAll("'", "''") + "'";
  const sql = fs
    .readFileSync('scripts/sql/leaderboard.template.sql', 'utf8')
    .replace(
      '-- @BALANCE_CATALOG@',
      () =>
        `insert into game_rank_private.balance(id,version,data) values(true,${quote(version)},${quote(JSON.stringify(payload))}::jsonb) on conflict(id) do update set version=excluded.version,data=excluded.data;`,
    )
    .replace(
      '-- @FOLD_FUNCTION@',
      () =>
        `create or replace function game_rank_private.fold(p_text text) returns text language sql immutable set search_path='' as $$ select lower(translate(normalize(coalesce(p_text,''),NFC),${quote(accented)},${quote(plain)})) $$;`,
    );
  fs.writeFileSync(
    'supabase/leaderboard.sql',
    '-- Generated by node scripts/generate-leaderboard-sql.mjs.\n' + sql,
  );
  const catalog = sql
    .split('\n')
    .find((line) => line.startsWith('insert into game_rank_private.balance'));
  if (!catalog) throw Error('Missing generated balance catalog');
  const projection = sql.slice(sql.indexOf('create or replace function game_rank_private.project('),sql.indexOf('create or replace function game_rank_private.refresh_entry('));
  if(!projection.includes('returns jsonb'))throw Error('Missing cosmetic profile projector');
  fs.writeFileSync('supabase/appearance-profiles.sql',`-- Generated: cosmetics catalog and public profile projection for existing leaderboard installs.
-- Run after leaderboard.sql; no private saves, wallets or access permissions are changed.
begin;
${catalog}
${projection}
do $$ declare saved record; begin
 for saved in select user_id,data,updated_at from public.saves loop
  perform game_rank_private.refresh_entry(saved.user_id,saved.data,saved.updated_at);
 end loop;
end $$;
commit;
`);
  fs.writeFileSync(
    'supabase/leaderboard-profile-levels.sql',
    `-- Generated by node scripts/generate-leaderboard-sql.mjs.
-- Existing leaderboard installation: update public projection limits and rebuild offline entries.
-- Private saves, EXP progression limits, timestamps and account permissions remain unchanged.
begin;
${catalog}
do $$ declare saved record; begin
 for saved in select user_id,data,updated_at from public.saves loop
  perform game_rank_private.refresh_entry(saved.user_id,saved.data,saved.updated_at);
 end loop;
end $$;
commit;
`,
  );
  console.log(
    `Leaderboard SQL generated; balance ${version}, ${Object.keys(payload.items).length} equipment definitions.`,
  );
} finally {
  await server.close();
}
