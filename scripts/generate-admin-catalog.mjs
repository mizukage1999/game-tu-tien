import fs from 'node:fs';
import { createServer } from 'vite';
const server = await createServer({
  configFile: false,
  envFile: false,
  server: { middlewareMode: true, watch: null },
});
try {
  const { ITEMS, DUNGEONS, QUESTS } = await server.ssrLoadModule('/src/data/index.ts');
  const { MAP_IDS, getMap } = await server.ssrLoadModule('/src/game/maps/index.ts');
  const { HEROES } = await server.ssrLoadModule('/src/data/heroes.ts');
  const rows = [];
  for (const [id, data] of Object.entries(ITEMS))
    rows.push(['item', id, { name: data.name, ...(data.slot ? { slot: data.slot } : {}) }]);
  for (const id of Object.keys(DUNGEONS)) rows.push(['dungeon', id, {}]);
  for (const id of Object.keys(QUESTS)) rows.push(['quest', id, {}]);
  for (const h of HEROES) rows.push(['hero', h.id, {}]);
  const { MONSTERS } = await server.ssrLoadModule('/src/data/index.ts');
  for (const id of MAP_IDS) {
    const map = getMap(id);
    rows.push(['map', id, { width: map.width, height: map.height }]);
    if (!map.arena && !map.private)
      for (const s of map.monsters)
        if (MONSTERS[s.type]?.boss)
          rows.push(['boss', id + ':' + s.type, { map: id, monster: s.type }]);
  }
  const unique = [...new Map(rows.map((r) => [r[0] + ':' + r[1], r])).values()];
  fs.writeFileSync(
    'supabase/admin-catalog.sql',
    `-- Generated by node scripts/generate-admin-catalog.mjs. Run after admin-operations.sql.\nbegin;\ndelete from public.game_admin_catalog;\ninsert into public.game_admin_catalog(kind,id,data) values\n` +
      unique
        .map(
          ([kind, id, data]) =>
            `('${kind}','${id.replaceAll("'", "''")}','${JSON.stringify(data).replaceAll("'", "''")}'::jsonb)`,
        )
        .join(',\n') +
      '\non conflict(kind,id) do update set data=excluded.data;\ncommit;\n',
  );
  console.log(`Admin server catalog: ${unique.length} definitions.`);
} finally {
  await server.close();
}
