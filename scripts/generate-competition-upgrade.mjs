import fs from 'node:fs';
const read = (name) => fs.readFileSync(`supabase/${name}.sql`, 'utf8');
const delivery = read('admin-delivery');
const claim = delivery.slice(
  delivery.indexOf('create or replace function public.claim_game_mail('),
  delivery.indexOf('create or replace function public.game_access_allowed('),
);
if (!claim.includes('activity:%')) throw Error('Regenerate admin-delivery.sql first.');
const parts = [
  read('admin-catalog'),
  read('leaderboard'),
  claim,
  read('competitive-play'),
  read('world-activities'),
  read('sky-race'),
];
const header = `-- Generated by node scripts/generate-competition-upgrade.mjs.
-- Existing online installation: schema, combat-expansion, player-access, alphatest-mail,
-- admin operations + item mail must already be installed. This upgrade preserves maintenance/access rules.
begin;
do $$ begin
 if to_regprocedure('public.claim_game_mail(uuid,uuid)') is null or to_regprocedure('public.game_access_allowed(uuid)') is null
 or to_regclass('public.game_admin_catalog') is null then raise exception 'Install the existing account, admin and mail migrations first';end if;
end $$;
`;
fs.writeFileSync(
  'supabase/competition-upgrade.sql',
  header +
    parts.map((p) => p.replace(/^\s*(?:begin|commit);\s*$/gim, '')).join('\n') +
    '\ncommit;\n',
);
console.log(
  'Generated supabase/competition-upgrade.sql: one atomic upgrade, preserving maintenance/access rules.',
);
